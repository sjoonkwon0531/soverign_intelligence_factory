import streamlit as st
from app_pages._ui import analyze, run_sc, data_badge, rng3

st.title("국가 소버린 AI 추진체계 시뮬레이터")
st.write("대한상공회의소 「국가 소버린 AI 추진체계 구축 방안」 보고서의 계량 모형을 누구나 직접 실행하고, 새 데이터로 다시 계산할 수 있도록 만든 도구입니다.")
data_badge()

R = analyze()
c = st.columns(4)
c[0].metric("프런티어 대비 표면 격차", f"{R['lag_f']:.1f}～{R['lag_f_hi']:.1f}년", help=f"{R['kr_best']} 기준, 환산 오차 ±{R['lag_band']:.2f}년")
c[1].metric("프런티어 상승 속도", f"연 {R['g_fr']:.1f}점", help=f"{R['window'][:7]} 이후 기록 경신 {R['g_fr_n']}개, 표준오차 {R['g_fr_se']:.2f}")
kr_rec = sum(v for k, v in R["records_all"].items() if "Korea" in k)
c[2].metric("한국의 세계 기록 경신", f"{kr_rec}건", help=f"{R['window'][:7]} 이후 프런티어 기록 경신 모델의 국적")
if "one_year_decades" in R:
    c[3].metric("1년 격차의 연산 환산", f"약 {10**R['one_year_decades']/1e4:,.0f}만 배", help="프런티어 상승 속도 ÷ 연산량 10배당 역량지수")

with st.spinner("기본 시나리오 계산 중"):
    s4 = run_sc("S4b", N=1000); s1 = run_sc("S1", N=1000)
c = st.columns(4)
c[0].metric("권고안 2029 도메인 게이트 확률", f"{s4['G2029_dom']:.2f}", delta=f"{s4['G2029_dom']-s1['G2029_dom']:+.2f} (분산 지속 대비)")
c[1].metric("권고안 2029 프런티어 격차", f"{s4['lag_front'][1]:.2f}년", delta=f"{s4['lag_front'][1]-s1['lag_front'][1]:+.2f}년", delta_color="inverse")
c[2].metric("권고안 누적 재무 갭", f"{s4['gap'][1]:.1f}조원", help=rng3(s4["gap"], 1, "조원"))
c[3].metric("권고안 주권 커버리지", f"{s4['sov']:.2f}", delta=f"{s4['sov']-s1['sov']:+.2f}")
st.caption("위 시나리오 수치는 1,000회 빠른 실행 값입니다. 보고서 재현은 시나리오 화면에서 3,000회로 실행하세요.")

st.subheader("사용 순서")
st.markdown("""
1. **데이터 관리**: 새 Epoch 자료, AA 점수, 한국 모델 점수를 올리거나 링크로 불러옵니다. 기준본과 무엇이 달라졌는지 바로 보여 줍니다.
2. **격차 진단과 모수 보정**: 새 자료로 격차 다층 구조를 다시 계산하고, 시뮬레이션 입력값(프런티어 속도, 연산 효과, 출발점 등)을 자동 보정합니다.
3. **격차 전망**: 2031년까지 프런티어와 한국의 격차를 시나리오별로 전망합니다. 흡수 경로 차단 조건도 볼 수 있습니다.
4. **시나리오 시뮬레이션**, **규모·지분 격자**: 추진체계 설계안을 비교하고 레버와 강건성을 점검합니다.
5. **비용편익과 ROI**, **공공수요 적산**: 순편익, NPV, IRR, 회수기간, 손익분기 전환율, 민감도, 부가가치를 계산합니다.
6. **민간 팩토리와 B2G 전용**: 대기업·프런티어 랩의 민간 AI 데이터센터가 있을 때 추진 방식별 성과와 국가 순편익을 비교합니다.
7. **국가 거시경제 파급**: AI 효과 중 국내에 귀속되는 부가가치(GNI 관점), 해외 서비스 수입, 접근 차단 손실을 2035년까지 비교합니다.
8. **예타식 종합 평가**: 사회적 할인율 4.5%의 편익비용비, 공공자금 한계비용, 경제성·정책성·기술성 가중 종합(AHP)을 계산합니다.
9. **전략 분석**: 결과를 좌우하는 모수(전역 민감도), 권고안이 불리해지는 세계(시나리오 발견), 중간 점검에서 멈출 권리의 가치(실물옵션)를 봅니다.
10. **결과 비교와 내보내기**: 저장한 실행 결과를 비교하고 엑셀로 내려받습니다.
""")
st.subheader("이 도구로 답할 수 있는 질문")
st.markdown("""
- 새 모델이 나와 격차가 바뀌면 권고안의 성공 확률과 재무 부담은 어떻게 달라지는가
- 같은 예산을 부처별로 나눌 때와 한 주체로 모을 때 무엇이 얼마나 다른가
- 민간이 대규모 AI 데이터센터를 짓는다면 국가 SPC는 여전히 필요한가, 필요하다면 어떤 규모와 형태인가
- 소버린 AI의 편익은 GDP가 아니라 어디에서 나오는가(국내 귀속, 수입 대체, 차단 위험)
- 어떤 불확실성이 결론을 뒤집는가, 그 신호를 언제 어떻게 관측해 멈출 것인가
""")
st.info("모든 확률과 금액은 명시된 가정에 따른 조건부 추정치입니다. 인용할 때는 시나리오 간 순위와 감도를 중심으로 하고, 기준일·모수·반복 횟수를 함께 적어 주세요.")
